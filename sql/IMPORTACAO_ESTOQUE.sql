create temp table mapa09(obra text primary key, almox uuid not null) on commit drop;
do $$ declare x record; oid uuid; aid uuid; n int; begin
for x in select distinct obra from inv09 loop
 select count(*) into n from public.obras where lower(trim(nome))=lower(x.obra);
 if n>1 then raise exception 'Obra ambígua: %',x.obra; end if;
 select id into oid from public.obras where lower(trim(nome))=lower(x.obra);
 if oid is null then insert into public.obras(nome,status) values(x.obra,'ativa') returning id into oid; end if;
 select count(*) into n from public.almoxarifados where obra_id=oid and ativo;
 if n>1 then raise exception 'Mais de um almoxarifado ativo: %',x.obra; end if;
 select id into aid from public.almoxarifados where obra_id=oid and ativo;
 if aid is null then insert into public.almoxarifados(nome,obra_id,ativo) values(x.obra,oid,true) returning id into aid; end if;
 insert into mapa09 values(x.obra,aid);
end loop; end $$;
